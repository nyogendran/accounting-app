"""Build a clause crosswalk from SRC-001 (S1) to SRC-007 (S7) from the two clause indexes. Read-only on
sources; writes one YAML file given as the first argument.

Text of a clause = its line range in the extraction, page markers and separators removed, whitespace
normalised. Matching, in order:
  1. same: identical text once list numbering, punctuation and case are ignored, one-to-one,
     preferring the same section and the nearest position (the clause ID may still differ);
  2. changed: for each remaining S1 clause, the best remaining S7 clause by difflib ratio, searched in
     the same section first and then everywhere; accepted when the ratio is at least 0.6;
  3. removed: S1 clauses left unmatched; new: S7 clauses left unmatched.
The 2.4.3 box clauses share line ranges, so their text is the anchor only (stated in the output).

Usage: python tools/sources/crosswalk_clauses.py <output.yaml>
"""
import collections
import difflib
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(r"C:\yogi\tiq-accounting-app")
SKIP = re.compile(r"^(Page \d+ of \d+|===== PAGE \d+ =====)$")
THRESHOLD = 0.6


def load(index_path, extract_path):
    lines = (ROOT / extract_path).read_text(encoding="utf-8").split("\n")
    data = yaml.safe_load((ROOT / index_path).read_text(encoding="utf-8"))
    out = []
    for c in data["clauses"]:
        a, b = c["lines"][0], c["lines"][-1]
        if str(c["section"]) == "2.4.3" and c.get("subheading") and "generated by the system" in c["subheading"]:
            text = c["anchor"]
        else:
            text = " ".join(l for l in lines[a - 1:b] if not SKIP.match(l.strip()))
        text = re.sub(r"\s+", " ", text).strip()
        out.append({"id": c["id"], "section": str(c["section"]), "page": c["page"], "kind": c["kind"], "text": text})
    return out


def key(text):
    # Ignore list numbering and punctuation-only differences when deciding "same".
    return re.sub(r"[^\w\[\]]+", " ", re.sub(r"^\d+\.\s*", "", text).lower()).strip()


s1 = load("docs/requirements/clause-index.yaml", "docs/sources/SRC-001-spec-v1/extracted/spec-v1.txt")
s7 = load("docs/requirements/clause-index-src007.yaml", "docs/sources/SRC-007-spec-v2.2/extracted/spec-v2.2.txt")
pos7 = {c["id"]: i for i, c in enumerate(s7)}
by_key7 = collections.defaultdict(list)
for c in s7:
    by_key7[key(c["text"])].append(c)

pairs, used7, left1 = [], set(), []
for i, c in enumerate(s1):
    cands = [d for d in by_key7.get(key(c["text"]), []) if d["id"] not in used7]
    if cands:
        cands.sort(key=lambda d: (d["section"] != c["section"], abs(pos7[d["id"]] - i)))
        d = cands[0]
        used7.add(d["id"])
        pairs.append({"s1": c["id"], "s7": d["id"], "status": "same", "ratio": 1.0})
    else:
        left1.append(c)

rest7 = [d for d in s7 if d["id"] not in used7]
by_section7 = collections.defaultdict(list)
for d in rest7:
    by_section7[d["section"]].append(d)
removed = []
for c in left1:
    best, best_ratio = None, 0.0
    for pool in (by_section7.get(c["section"], []), rest7):
        for d in pool:
            if d["id"] in used7:
                continue
            m = difflib.SequenceMatcher(None, c["text"], d["text"], autojunk=False)
            if m.real_quick_ratio() < best_ratio or m.quick_ratio() < best_ratio:
                continue
            r = m.ratio()
            if r > best_ratio:
                best, best_ratio = d, r
        if best_ratio >= THRESHOLD:
            break
    if best is not None and best_ratio >= THRESHOLD:
        used7.add(best["id"])
        pairs.append({"s1": c["id"], "s7": best["id"], "status": "changed", "ratio": round(best_ratio, 3)})
    else:
        removed.append(c["id"])

new = [d["id"] for d in s7 if d["id"] not in used7]
order1 = {c["id"]: i for i, c in enumerate(s1)}
pairs.sort(key=lambda p: order1[p["s1"]])
counts = collections.Counter(p["status"] for p in pairs)
moved = sum(1 for p in pairs if p["s1"].split("-")[1] != p["s7"].split("-")[1])
doc = {
    "version": 1,
    "from": {"source": "SRC-001", "index": "docs/requirements/clause-index.yaml"},
    "to": {"source": "SRC-007", "index": "docs/requirements/clause-index-src007.yaml"},
    "method": (__doc__ or "").strip(),
    "counts": {"s1_clauses": len(s1), "s7_clauses": len(s7), "same": counts["same"], "changed": counts["changed"],
               "removed": len(removed), "new": len(new), "pairs_in_a_different_section": moved},
    "pairs": pairs,
    "removed": removed,
    "new": new,
}
Path(sys.argv[1]).write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
print(doc["counts"])
